'use strict';
// scripts/make-web-data.js - bench/results.json → web/bench-data.js
const fs   = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const inPath  = path.join(root, 'bench', 'results.json');
const outPath = path.join(root, 'docs', 'bench-data.js');

if (!fs.existsSync(inPath)) {
  console.error(`Missing ${inPath}. Run \`npm run bench\` first.`);
  process.exit(1);
}

const raw = JSON.parse(fs.readFileSync(inPath, 'utf8'));
const compact = {
  trials:     raw.trials     || 0,
  cooldownMs: raw.cooldownMs || 0,
  system:     raw.system     || {},
  table:      raw.table      || [],
};

const js =
  '/* auto-generated by scripts/make-web-data.js - do not edit directly */\n' +
  '/* Regenerate with: npm run build:web                              */\n' +
  'window.BENCH = ' + JSON.stringify(compact) + ';\n';

fs.writeFileSync(outPath, js);
console.log(`Wrote web/bench-data.js - ${compact.table.length} rows, ${compact.trials} trials`);

if (!compact.system || !compact.system.cpu) {
  console.warn('⚠ bench/results.json has no system info - was it produced by the updated bench/runner.js?');
}